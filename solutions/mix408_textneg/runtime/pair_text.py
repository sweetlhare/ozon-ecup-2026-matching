"""Выровненная подача пары товаров: поле — значение A — значение B.

Обычный вход cross-encoder'а («name1 ; json1» [SEP] «name2 ; json2») заставляет
модель выравнивать схемы самостоятельно, а они не совпадают: key-Jaccard между
карточками пары в среднем 0.082, у 24.3% пар общих ключей нет вообще — одна
пишет «цвет», другая «цвет товара», одна «российский размер», другая «размер
производителя».

Здесь ключи канонизируются, мусорные выбрасываются (они съедают ~20% символов,
а различают позитивы и негативы хуже случайного), и пара подаётся выровненной:
    цвет: чёрный | серый ; размер: 42 | 42 ; бренд: nike | nike
Совпадение и конфликт становятся видны локально, а не через весь текст.
"""
import json
import re

import pandas as pd

from attr_canon import CANON as CANON_AUTO, norm_value

# синонимы -> канонический ключ
CANON = {}
for canon, variants in {
    "цвет": ("цвет товара", "цвет", "название цвета", "основной цвет", "цвет производителя"),
    "бренд": ("бренд", "производитель", "торговая марка", "бренд в одежде и обуви"),
    "артикул": ("артикул", "партномер (артикул производителя)", "артикул производителя",
                "артикул поставщика", "код продавца", "номер модели"),
    "размер": ("размер", "российский размер", "размер производителя", "размер одежды",
               "размер обуви"),
    "страна": ("страна-изготовитель", "страна производства", "страна изготовитель"),
    "материал": ("материал", "материал изделия", "основной материал"),
    "модель": ("модель", "название модели"),
    "пол": ("пол", "целевая аудитория", "пол ребенка"),
    "вес": ("вес товара, г", "вес", "вес товара без упаковки (г)", "вес, г"),
    "объем": ("объем", "объем, л", "объем товара"),
    "количество": ("единиц в одном товаре", "количество в упаковке", "количество деталей",
                   "количество предметов"),
    "тип": ("тип", "вид товара", "тип товара"),
    "назначение": ("назначение", "предназначено для", "назначение средства"),
    "возраст": ("рекомендуемый возраст", "возраст", "минимальный возраст ребенка"),
}.items():
    for v in variants:
        CANON[v] = canon

CANON.update({k: v for k, v in CANON_AUTO.items() if k not in CANON})

# ключи без различающей силы: совпадают у негативов не реже, чем у позитивов
DROP = {
    "валюта", "гарантийный срок", "длина упаковки", "высота упаковки", "ширина упаковки",
    "комплектация", "состав", "условия хранения", "срок годности", "срок годности в днях",
    "упаковка", "особенности", "количество заводских упаковок", "вес с упаковкой (г)",
    "размер упаковки", "гарантия",
}

# Порядок вывода: сначала самые информативные поля. Порядок важен, потому что
# хвост обрезается по max_fields и max_len.
#
# Замер различающей силы ВНУТРИ категории (доля совпадений у позитивов минус
# у негативов, 60k пар, усреднение по категориям — глобальный замер обманывает,
# как было с «полом»: +0.180 глобально против +0.002 внутри категории):
#   объем +0.234, вес +0.221, цвет +0.208, количество +0.163, артикул +0.158,
#   модель +0.118, назначение +0.112, материал +0.074, страна +0.064,
#   бренд +0.029, размер +0.022, тип +0.022, пол +0.002, возраст -0.031.
# Бренд стоял первым, а различает почти нулево: негативы — товары того же
# бренда, retrieval их и подбирает.
PRIORITY = ["объем", "вес", "цвет", "количество", "артикул", "модель",
            "назначение", "материал", "страна", "бренд", "размер", "тип",
            "пол", "возраст"]
# прежний порядок: модели v13/v17/v18 обучены на нём, им нужен тот же вход
PRIORITY_V1 = ["бренд", "артикул", "модель", "цвет", "размер", "пол", "материал",
               "количество", "объем", "вес", "тип", "назначение", "возраст", "страна"]
_PRI = {k: i for i, k in enumerate(PRIORITY_V1)}
_PRI_V2 = {k: i for i, k in enumerate(PRIORITY)}

# Порядок полей отдельно для каждой категории (src/pri_by_cat.json, считается
# скриптом в scratchpad: сила = (совпадение у позитивов − у негативов) × sqrt(покрытие)).
#
# Глобальный порядок вводит в заблуждение: бренд в среднем по категориям даёт
# +0.029, но в Одежде это +0.481, а в Обуви +0.348 — сильнейший признак, тогда
# как в Электронике и Бытовой химии он не различает ничего (негативы там —
# товары того же бренда, их и подбирает retrieval). Одежда и Обувь при этом
# наши худшие категории (PR-AUC 0.579 и 0.590 против 0.82 в среднем), а метрика
# macro — они весят столько же, сколько «Аптека» с 0.946.
_PRI_BY_CAT = {}
try:
    import json as _json
    import os as _os
    _p = _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "pri_by_cat.json")
    with open(_p, encoding="utf-8") as _fh:
        _PRI_BY_CAT = {c: {k: i for i, k in enumerate(ks)}
                       for c, ks in _json.load(_fh).items()}
except (OSError, ValueError):
    pass

_ws = re.compile(r"\s+")

# поля, где приведение единиц работает в минус: у негативов после нормализации
# совпадений больше, чем у позитивов («гарантия 12 месяцев» есть у всех)
NO_NORM = {"гарантийный срок", "срок годности", "диаметр", "толщина столешницы"}


def parse(raw: str, normalize_units: bool = True) -> dict:
    """JSON-строка -> канонизированный dict без мусорных полей.

    Приведение величин к базовым единицам — главный рычаг: «0.5 л» и «500 мл»
    это одно и то же, но текстово разное, а модель арифметику не выполняет.
    Измерено: различающая сила числовых полей растёт с +0.048 до +0.228,
    затрагивает 14% пар. Нормализовать нужно ДО канонизации ключа, потому что
    единица часто живёт в имени ключа («объем, л»).
    """
    try:
        d = json.loads(raw)
        if not isinstance(d, dict):
            return {}
    except Exception:  # noqa: BLE001
        return {}
    out = {}
    for k, v in d.items():
        k0 = str(k).strip().lower()
        if k0 in DROP:
            continue
        v = _ws.sub(" ", str(v).strip().lower())
        if normalize_units and k0 not in NO_NORM:
            v = norm_value(k0, v)
        v = v[:60]
        k = CANON.get(k0, k0)
        if v and k not in out:
            out[k] = v
    return out


# Словарь брендов из атрибутов всего каталога. Бренд — сильнейший признак в слабых
# категориях (разница совпадения у позитивов и негативов +0.348 в Обуви, +0.481
# в Одежде), но в атрибутах он задан у обоих товаров лишь в 22% и 6% пар. В названии
# он есть гораздо чаще: извлечение по словарю поднимает покрытие до 76% и 43%,
# сохраняя различающую силу (+0.191 и +0.249). Вклад признака (сила x покрытие)
# вырастает вдвое в Обуви и в 3.7 раза в Одежде.
_BRANDS = set()
try:
    import json as _j
    import os as _o
    with open(_o.path.join(_o.path.dirname(_o.path.abspath(__file__)), "brands.json"),
              encoding="utf-8") as _f:
        _BRANDS = set(_j.load(_f))
except (OSError, ValueError):
    pass


def brand_from_name(name: str) -> str:
    """Бренд из названия: первые одно-два слова или любое слово-бренд длиннее двух букв."""
    if not _BRANDS or not name:
        return ""
    parts = name.split()
    for n in (2, 1):
        cand = " ".join(parts[:n])
        if cand in _BRANDS:
            return cand
    for w in parts:
        if len(w) > 2 and w in _BRANDS:
            return w
    return ""


def item_attrs(items: pd.DataFrame, with_category: bool = False,
               fill_brand: bool = False) -> dict:
    """id -> (name, канонизированные атрибуты).

    С `with_category` категория приписывается к имени. Обычная подача
    (`item_texts`) её содержит, а выровненная — нет, хотя метрика считается
    покатегорийно и категория задаёт, какое поле решает исход: в обуви размер,
    в ювелирке вставка. Флаг, а не безусловное добавление, потому что модели
    v13/v17 обучены без неё и им нужен прежний вход.
    """
    name = items["name"].astype(str).str.lower()
    if with_category and "category" in items.columns:
        name = items["category"].astype(str).str.lower() + " ; " + name
    cats = (items["category"].astype(str).tolist() if "category" in items.columns
            else [""] * len(items))
    attrs = [parse(s) for s in items["attributes"].astype(str).tolist()]
    if fill_brand:
        nm_low = items["name"].astype(str).str.lower().tolist()
        for d, t in zip(attrs, nm_low):
            if "бренд" not in d:
                b = brand_from_name(t)
                if b:
                    d["бренд"] = b
    return dict(zip(items["id"].tolist(), zip(name.tolist(), attrs, cats)))


def pair_text(a, b, max_fields: int = 24, pri=None) -> tuple:
    """Возвращает (текст A, текст B) для подачи в cross-encoder.

    Первая часть — названия, вторая — выровненные поля: общие ключи идут
    парой значений, дальше то, что есть только у одной стороны.
    """
    na, aa, ca = a[0], a[1], (a[2] if len(a) > 2 else "")
    nb, ab = b[0], b[1]
    if pri == "bycat":
        pri = _PRI_BY_CAT.get(ca) or _PRI_V2
    elif pri is None:
        pri = _PRI
    common = sorted(set(aa) & set(ab), key=lambda k: (pri.get(k, 99), k))
    only_a = sorted(set(aa) - set(ab), key=lambda k: (pri.get(k, 99), k))
    only_b = sorted(set(ab) - set(aa), key=lambda k: (pri.get(k, 99), k))

    left, right = [na], [nb]
    for k in common[:max_fields]:
        left.append(f"{k}: {aa[k]}")
        right.append(f"{k}: {ab[k]}")
    rest = max(0, max_fields - len(common))
    for k in only_a[:rest // 2]:
        left.append(f"{k}: {aa[k]}")
    for k in only_b[:rest // 2]:
        right.append(f"{k}: {ab[k]}")
    return " ; ".join(left), " ; ".join(right)
