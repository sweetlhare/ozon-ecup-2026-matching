def key_unit(key: str) -> str:
    m = KEY_UNIT.search(key.lower().replace("ё", "е").strip())
    if not m:
        return ""
    u = m.group(1)
    return LONG.get(u, u)


def canon_value(val: str, kunit: str = ""):
    """('42.0 г', 'm') если удалось привести к базовой единице, иначе (None, None)."""
    m = NUM.match(val)
    if not m:
        return None, None
    num = float(m.group(1).replace(",", "."))
    u = m.group(2).strip(".")
    if not u:
        u = kunit
    if not u:
        return None, None
    info = UNITS.get(u)
    if not info:
        return None, None
    dim, mult = info
    x = num * mult
    return f"{x:.6g}", dim


